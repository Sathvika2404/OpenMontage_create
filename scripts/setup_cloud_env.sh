#!/usr/bin/env bash
# Reusable setup for sandboxed cloud environments (e.g. Claude Code on the web).
#
# These environments typically allow npm + PyPI + Hugging Face but block
# browser downloads and the jsDelivr CDN. This script installs everything
# OpenMontage's local render/voice path needs and points it at local copies:
#
#   - Python deps (requirements.txt) + Playwright + Piper TTS
#   - remotion-composer node_modules (npm ci)
#   - GSAP vendored into .vendor/ (used instead of cdn.jsdelivr.net)
#   - HyperFrames CLI warmed into the npx cache
#   - Piper voice model downloaded to an explicit directory
#   - Pre-installed Chromium wired up for Remotion + HyperFrames
#
# It writes .env.local-runtime (gitignored, no secrets) with the resolved
# paths. Load it with:   source .env.local-runtime
#
# Idempotent: safe to re-run; already-present pieces are skipped.
#
# Usage: scripts/setup_cloud_env.sh [--skip-python] [--skip-node]
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

PYTHON="${PYTHON:-python3}"
PLAYWRIGHT_VERSION="${PLAYWRIGHT_VERSION:-1.56.0}"
GSAP_VERSION="${GSAP_VERSION:-3.14.2}"           # keep in sync with lib/local_runtime.py
HYPERFRAMES_VERSION="${HYPERFRAMES_VERSION:-}"  # empty = latest, as upstream
PIPER_VOICE="${PIPER_VOICE:-en_US-lessac-medium}"
PIPER_MODEL_DIR="${PIPER_MODEL_DIR:-$HOME/.piper/models}"
OPENMONTAGE_VENDOR_DIR="${OPENMONTAGE_VENDOR_DIR:-$REPO_ROOT/.vendor}"
ENV_OUT="$REPO_ROOT/.env.local-runtime"

SKIP_PYTHON=0
SKIP_NODE=0
for arg in "$@"; do
  case "$arg" in
    --skip-python) SKIP_PYTHON=1 ;;
    --skip-node) SKIP_NODE=1 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

log() { printf '==> %s\n' "$*"; }
warn() { printf '  [warn] %s\n' "$*" >&2; }

# ---- Python ----------------------------------------------------------------
if [ "$SKIP_PYTHON" -eq 0 ]; then
  log "Installing Python dependencies (requirements.txt, playwright==$PLAYWRIGHT_VERSION, piper-tts)"
  # PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD keeps pip from fetching browsers; we
  # use the pre-installed ones instead. Never run `playwright install` here.
  PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD=1 "$PYTHON" -m pip install -q \
    -r requirements.txt "playwright==$PLAYWRIGHT_VERSION" piper-tts
fi

# ---- Node ------------------------------------------------------------------
if [ "$SKIP_NODE" -eq 0 ]; then
  command -v npm >/dev/null || { echo "npm not found on PATH" >&2; exit 1; }

  if [ ! -d remotion-composer/node_modules/remotion ]; then
    log "Installing remotion-composer dependencies (npm ci)"
    (cd remotion-composer && npm ci --no-audit --no-fund)
  else
    log "remotion-composer node_modules present — skipping npm ci"
  fi

  GSAP_FILE="$OPENMONTAGE_VENDOR_DIR/node_modules/gsap/dist/gsap.min.js"
  if [ ! -f "$GSAP_FILE" ]; then
    log "Vendoring gsap@$GSAP_VERSION into $OPENMONTAGE_VENDOR_DIR"
    mkdir -p "$OPENMONTAGE_VENDOR_DIR"
    npm install --prefix "$OPENMONTAGE_VENDOR_DIR" --no-audit --no-fund --no-save \
      "gsap@$GSAP_VERSION" >/dev/null
  else
    log "GSAP already vendored at $GSAP_FILE"
  fi

  log "Warming HyperFrames CLI into the npx cache"
  HF_PKG="hyperframes${HYPERFRAMES_VERSION:+@$HYPERFRAMES_VERSION}"
  npx --yes "$HF_PKG" --version >/dev/null 2>&1 \
    || warn "HyperFrames warm-up failed; first render will fetch on demand"
fi

# ---- Piper voice -----------------------------------------------------------
mkdir -p "$PIPER_MODEL_DIR"
PIPER_MODEL_PATH="$PIPER_MODEL_DIR/$PIPER_VOICE.onnx"
if [ -f "$PIPER_MODEL_PATH" ] && [ -f "$PIPER_MODEL_PATH.json" ]; then
  log "Piper voice present: $PIPER_MODEL_PATH"
else
  log "Downloading Piper voice $PIPER_VOICE to $PIPER_MODEL_DIR"
  "$PYTHON" -m piper.download_voices --download-dir "$PIPER_MODEL_DIR" "$PIPER_VOICE" \
    || warn "Piper voice download failed; piper_tts will be unavailable until a model is placed in $PIPER_MODEL_DIR"
fi

# ---- Browser ---------------------------------------------------------------
BROWSER="$("$PYTHON" -c 'from lib.local_runtime import resolve_browser_executable as r; print(r() or "")')"
if [ -n "$BROWSER" ]; then
  log "Using local browser: $BROWSER"
else
  warn "No local Chromium found; Remotion/HyperFrames will try to download one"
fi

# ---- Write env file --------------------------------------------------------
log "Writing $ENV_OUT"
{
  echo "# Generated by scripts/setup_cloud_env.sh — local paths only, no secrets."
  echo "# Load with: source .env.local-runtime"
  echo "export PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD=1"
  echo "export OPENMONTAGE_VENDOR_DIR=\"$OPENMONTAGE_VENDOR_DIR\""
  echo "export PIPER_MODEL_DIR=\"$PIPER_MODEL_DIR\""
  echo "export PIPER_MODEL_PATH=\"$PIPER_MODEL_PATH\""
  if [ -n "$BROWSER" ]; then
    echo "export OPENMONTAGE_BROWSER_EXECUTABLE=\"$BROWSER\""
    echo "export REMOTION_BROWSER_EXECUTABLE=\"$BROWSER\""
    echo "export HYPERFRAMES_BROWSER_PATH=\"$BROWSER\""
  fi
} > "$ENV_OUT"

# Claude Code SessionStart hooks expose CLAUDE_ENV_FILE; persist there too so
# later Bash calls in the session inherit the paths.
if [ -n "${CLAUDE_ENV_FILE:-}" ]; then
  grep -v '^#' "$ENV_OUT" >> "$CLAUDE_ENV_FILE"
fi

# ---- Summary ---------------------------------------------------------------
log "Summary"
# shellcheck disable=SC1090
source "$ENV_OUT"
"$PYTHON" - <<'PY'
import shutil
from lib.local_runtime import resolve_browser_executable, resolve_gsap_path, resolve_piper_model
import os

def row(label, value):
    print(f"    {label:<18} {value or 'NOT FOUND'}")

row("browser", resolve_browser_executable())
row("gsap", resolve_gsap_path())
row("piper cli", shutil.which("piper"))
row("piper model", resolve_piper_model(os.path.basename(os.environ["PIPER_MODEL_PATH"])[:-5]))
row("ffmpeg", shutil.which("ffmpeg"))
row("node", shutil.which("node"))
PY
log "Done. Run: source .env.local-runtime"
